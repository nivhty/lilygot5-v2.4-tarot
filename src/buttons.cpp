#include "buttons.h"
#include <AceButton.h>
#include "../include/t5_pins.h"
#include "../include/config.h"
#include "tarot.h"

using namespace ace_button;

static AceButton button1;
static AceButton bootButton;
static ButtonEvent currentEvent = BTN_NONE;

// If a button is already held at boot (e.g. the press that woke the device),
// swallow its events until it has been released once.
static bool suppressButton1 = false;
static bool suppressBoot = false;

static void buttonEventHandler(AceButton* button, uint8_t eventType, uint8_t buttonState) {
    // Button timing is a nice source of user entropy ("cutting the deck")
    tarotAddEntropy(micros());

    const bool isBtn1 = button->getPin() == BUTTON_1_PIN;
    if ((isBtn1 && suppressButton1) || (!isBtn1 && suppressBoot)) return;

    Serial.printf("[BUTTON] Pin %d (%s) event %s\n",
                  button->getPin(), isBtn1 ? "Button 1" : "BOOT",
                  eventType == AceButton::kEventClicked ? "CLICK" :
                  eventType == AceButton::kEventLongPressed ? "LONG_PRESS" : "OTHER");

    if (eventType == AceButton::kEventClicked) {
        currentEvent = isBtn1 ? BTN1_CLICK : BOOT_CLICK;
    } else if (eventType == AceButton::kEventLongPressed) {
        currentEvent = isBtn1 ? BTN1_LONG_PRESS : BOOT_LONG_PRESS;
    }
}

void setupButtons() {
    pinMode(BUTTON_1_PIN, INPUT);           // GPIO39 has no internal pull-up (external on board)
    pinMode(BUTTON_BOOT_PIN, INPUT_PULLUP);

    ButtonConfig* config = ButtonConfig::getSystemButtonConfig();
    config->setEventHandler(buttonEventHandler);
    config->setFeature(ButtonConfig::kFeatureClick);
    config->setFeature(ButtonConfig::kFeatureLongPress);
    config->setFeature(ButtonConfig::kFeatureSuppressAfterLongPress);
    config->setLongPressDelay(LONG_PRESS_MS);
    config->setClickDelay(CLICK_MAX_MS);

    button1.init((uint8_t)BUTTON_1_PIN, HIGH, 0);
    bootButton.init((uint8_t)BUTTON_BOOT_PIN, HIGH, 1);

    suppressButton1 = digitalRead(BUTTON_1_PIN) == LOW;
    suppressBoot = digitalRead(BUTTON_BOOT_PIN) == LOW;
}

void checkButtons() {
    button1.check();
    bootButton.check();

    // Clear suppression only once the pin has been released for longer than AceButton's
    // debounce window, so the click generated by releasing a held wake-press is still swallowed.
    static uint32_t btn1HighSince = 0, bootHighSince = 0;
    const uint32_t now = millis();
    if (digitalRead(BUTTON_1_PIN) == LOW) btn1HighSince = now;
    else if (suppressButton1 && now - btn1HighSince > 100) suppressButton1 = false;
    if (digitalRead(BUTTON_BOOT_PIN) == LOW) bootHighSince = now;
    else if (suppressBoot && now - bootHighSince > 100) suppressBoot = false;

    // Failsafe: never remain permanently suppressed
    if (now > 1500) {
        suppressButton1 = false;
        suppressBoot = false;
    }
}

ButtonEvent consumeButtonEvent() {
    ButtonEvent evt = currentEvent;
    currentEvent = BTN_NONE;

    // Ignore events that happen immediately after boot/wake
    if (millis() < WAKE_GUARD_MS) return BTN_NONE;
    return evt;
}
