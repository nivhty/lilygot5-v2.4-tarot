#ifndef CONFIG_H
#define CONFIG_H

// --- Timing ---
#define INACTIVITY_TIMEOUT_MS   20000   // 20 s idle -> light sleep (instant wake, screen state kept)
#define DEEP_SLEEP_AFTER_MS     600000  // 10 min idle -> deep sleep (lowest power, cold boot on wake)
#define IDLE_CHARGER_POLL_MS    5000    // Wake from light sleep this often to check for a charger
#define LONG_PRESS_MS           500     // 500 ms long press threshold (BOOT hold -> cover)
#define CLICK_MAX_MS            450     // Max press duration still counted as a click
#define WAKE_GUARD_MS           500     // Ignore button events right after boot/wake
#define SHUFFLE_FRAMES          5       // Number of shuffle animation frames
#define SHUFFLE_FRAME_MS        50      // Extra delay between frames

// --- Display (Vertical / Portrait: 122 x 250) ---
#define SCREEN_WIDTH            122
#define SCREEN_HEIGHT           250
#define BASE_ROTATION           0       // 0: Portrait (or 2 if inverted)
#define FULL_REFRESH_EVERY      6       // Force a full refresh after this many partial updates (anti-ghosting)

// --- Card bitmap (generated by tools/convert_images.py --size 120x220) ---
#define CARD_IMG_WIDTH          120
#define CARD_IMG_HEIGHT         220

// --- Spread ---
#define SPREAD_SIZE             3       // Past / Present / Future

// --- Battery ---
#define BATTERY_FULL_MV         4200
#define BATTERY_EMPTY_MV        3300
#define BATTERY_CHARGING_MV     4250    // Above this the cell can only be on a charger
#define CHARGE_JUMP_MV          60      // Voltage step that indicates plug/unplug
#define CHARGING_SCREEN_MS      3000    // How long the charging notice stays up

#endif // CONFIG_H
